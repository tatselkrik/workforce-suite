create function hris_private.regional_wage_compute(s jsonb)returns jsonb language plpgsql immutable security invoker set search_path=''as $fn$
declare lo date;hi date;on_day date;p jsonb;c jsonb;rate jsonb;found jsonb;matches jsonb;result jsonb:='[]';d jsonb;state text;blocking integer:=0;exemptions integer:=0;max_required bigint:=0;max_gap bigint:=0;required bigint;gap bigint;den bigint;num numeric;cid uuid;eid uuid;
begin
 cid:=(s->>'company_id')::uuid;eid:=(s->>'employee_id')::uuid;lo:=(s->>'starts_on')::date;hi:=(s->>'ends_on')::date;p:=s->'pay';
 if cid is null or eid is null or cid='00000000-0000-0000-0000-000000000000'or eid='00000000-0000-0000-0000-000000000000'or lo is null or hi is null or lo>hi or extract(year from lo)<>2026 or extract(year from hi)<>2026 then raise exception 'Use a bounded2026 wage-review period.'using errcode='23514';end if;
 if((p->>'basis')in('daily','monthly'))is not true or(p->>'rate_cents')is null or(p->>'rate_cents')::bigint not between 1 and 10000000000 or(p->>'annual_divisor')is null or(p->>'annual_divisor')::integer not in(365,366)then raise exception 'Check recorded basic salary/divisor.'using errcode='23514';end if;
 if jsonb_typeof(s->'classifications')is distinct from'array'or jsonb_array_length(s->'classifications')>128 or exists(select 1 from jsonb_array_elements(s->'classifications')x where(x->>'company_id')::uuid is distinct from cid or(x->>'employee_id')::uuid is distinct from eid)then raise exception 'Classification outside person/company.'using errcode='23514';end if;
 for on_day in select v::date from generate_series(lo,hi,interval'1day')v loop
  state:='missing_classification';c:=null;rate:=null;required:=null;gap:=null;
  select coalesce(jsonb_agg(x order by x->>'id'),'[]')into found from jsonb_array_elements(s->'classifications')x where x->>'status'='approved'and(x->>'starts_on')::date<=on_day and(x->>'ends_on')::date>=on_day;
  if jsonb_array_length(found)>1 then state:='overlapping_classifications';
  elsif jsonb_array_length(found)=1 then
   c:=found->0;
   if c->>'approved_by'is null or c->>'approved_at'is null or c->>'approved_by'in(c->>'created_by',c->>'prepared_by')then state:='unreviewed_classification';
   elsif c->'employee_basis'is distinct from s->'employee_basis'then state:='workplace_or_employment_changed';
   elsif c->>'coverage'='exempt'then
    if btrim(coalesce(c->>'evidence',''))=''or btrim(coalesce(c->>'note',''))=''then state:='unreviewed_exemption';else state:='documented_exemption';exemptions:=exemptions+1;end if;
   elsif c->>'coverage'='covered'then
    state:='rate_not_verified';
    select coalesce(jsonb_agg(x),'[]')into matches from jsonb_array_elements(hris_private.regional_wage_catalog()->'rates')x where x->>'series_key'=c->>'series_key'and(x->>'starts_on')::date<=on_day and(x->>'ends_on')::date>=on_day;
    if jsonb_array_length(matches)=1 then
     rate:=matches->0;num:=(rate->>'daily_basic_cents')::bigint;den:=1;
     if p->>'basis'='monthly'then num:=num*(p->>'annual_divisor')::integer;den:=12;end if;
     required:=ceil(num/den)::bigint;gap:=greatest(required-(p->>'rate_cents')::bigint,0);
     state:=case when(p->>'rate_cents')::numeric*den>=num then'meets_recorded_floor'else'below_recorded_floor'end;
     max_required:=greatest(max_required,required);max_gap:=greatest(max_gap,gap);
    end if;
   else state:='nonstandard_coverage_needs_review';end if;
  end if;
  if state not in('meets_recorded_floor','documented_exemption')then blocking:=blocking+1;end if;
  d:=jsonb_build_object('date',on_day,'status',state,'classification_id',c->'id','classification_revision',c->'revision','rate_id',rate->'id','floor_daily_cents',rate->'daily_basic_cents','required_salary_cents',required,'gap_salary_cents',gap);
  result:=result||jsonb_build_array(d);
 end loop;
 return jsonb_build_object('version',hris_private.regional_wage_catalog()->'version','starts_on',lo,'ends_on',hi,'blocking_days',blocking,'exemption_days',exemptions,'max_required_salary_cents',max_required,'max_gap_salary_cents',max_gap,'days',result);
end;$fn$;
